#!/usr/bin/env node
/**
 * Build the test-only S10 fault-injection products on the Darwin ARM64 producer host.
 *
 * Usage: node packages/geospec-engine/qualification/s10/build-injected.mjs native|wasm --out <dir>
 *   native  NAPI addon with the `s10-fault-injection` Cargo feature and the bridge's
 *           GEOSPEC_S10_INJECT; GEOSPEC_S10_FAULT selects the Rust panic or C++ exception cell.
 *   wasm    Mixed WASM module whose bridge executes a trap on its first STEP open.
 * The products use the prepared OCCT generation of `ci-native` and `ci-wasm`. The generated bridge header exists only while this script runs and
 * is removed afterwards, so a release target in the same checkout never sees it.
 * Exit: 0 with the products in <dir>; 1 on a refused host or failed build.
 */
import { spawnSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

const here = dirname(fileURLToPath(import.meta.url));
const engineRoot = resolve(here, '../..');
const root = resolve(engineRoot, '../..');
const cacheRoot = join(root, 'node_modules/.cache/geospec-engine-native');
const header = join(engineRoot, 'native/occt/bridge/geospec_s10_inject.local.h');

const run = (command, args, options = {}) => {
  const result = spawnSync(command, args, { cwd: root, stdio: ['inherit', 'inherit', 'inherit'], ...options });
  if (result.status !== 0) {
    throw new Error(`${command} ${args.join(' ')} failed with ${result.status ?? result.signal}`);
  }
  return result;
};

const capture = (command, args, options = {}) =>
  String(run(command, args, { ...options, stdio: ['ignore', 'pipe', 'inherit'], encoding: 'utf8' }).stdout).trim();

/** The environment `ci-products.mjs` gives each producer step for the selected generation. */
const producerEnvironment = () => {
  const generation = capture('python3', ['-B', join(engineRoot, 'scripts/prepare-delivery.py'), 'generation']);
  if (!/^[0-9a-f]{64}$/u.test(generation)) {
    throw new Error('Invalid GeoSpec delivery generation.');
  }
  const cache = join(cacheRoot, 'delivery-wasm-eh/generations', generation);
  mkdirSync(cache, { recursive: true });
  return {
    ...process.env,
    NX_DAEMON: 'false',
    pnpm_config_verify_deps_before_run: 'warn', // oxlint-disable-line camelcase -- Exact pnpm setting name.
    GEOSPEC_DELIVERY_CACHE: cache,
    GEOSPEC_DELIVERY_GENERATION: generation,
    GEOSPEC_OCCT_PREFIX: join(cache, 'occt-native/install'),
    GEOSPEC_MIXED_INPUTS: join(cache, 'mixed-inputs-simd128.json'),
  };
};

const runTarget = (target, env) => {
  run('pnpm', ['nx', 'run', `geospec-engine:${target}`, '--skip-nx-cache', '--excludeTaskDependencies'], { env });
};

const prepare = (env, stages) => {
  if (process.platform !== 'darwin' || process.arch !== 'arm64') {
    throw new Error(
      `The GeoSpec delivery recipe builds on Darwin ARM64 only; this host is ${process.platform}-${process.arch}.`,
    );
  }
  for (const stage of stages) {
    runTarget(`prepare-delivery:${stage}`, env);
  }
};

const writeHeader = (cell) => {
  const lines = ['// Generated by qualification/s10/build-injected.mjs; never commit.', '#define GEOSPEC_S10_INJECT 1'];
  if (cell !== undefined) {
    lines.push(`#define GEOSPEC_S10_INJECT_CELL "${cell}"`);
  }
  writeFileSync(header, `${lines.join('\n')}\n`);
};

const native = (env, out) => {
  prepare(env, ['sources', 'tools', 'prefixes']);
  writeHeader();
  const toolchain = dirname(capture('rustup', ['which', '--toolchain', '1.88', 'rustc']));
  const recipe = JSON.parse(readFileSync(join(engineRoot, 'scripts/selected-delivery.json'), 'utf8'));
  const cargoHome = process.env['CARGO_HOME'] ?? join(process.env['HOME'] ?? '', '.cargo');
  run(
    'pnpm',
    [
      '--dir',
      engineRoot,
      'exec',
      'napi',
      'build',
      '--manifest-path',
      'bindings/node/Cargo.toml',
      '--target',
      'aarch64-apple-darwin',
      '--release',
      '--platform',
      '--no-js',
      '--features',
      's10-fault-injection',
      '--output-dir',
      out,
      '--target-dir',
      join(cacheRoot, 's10-node-target'),
      '--',
      '--locked',
    ],
    {
      env: {
        ...env,
        PATH: `${toolchain}:${env['PATH']}`,
        MACOSX_DEPLOYMENT_TARGET: recipe.macosDeploymentTarget,
        // An injected product is never a verified release producer.
        GEOSPEC_PRODUCER_ROUTE: 's10-fault-injection',
        GEOSPEC_PRODUCER_CARGO_CWD: engineRoot,
        GEOSPEC_PRODUCER_MANIFEST: 'bindings/node/Cargo.toml',
        RUSTFLAGS: `--remap-path-prefix=${root}=tau --remap-path-prefix=${cargoHome}=cargo`,
      },
    },
  );
  const addons = readdirSync(out).filter((name) => name.endsWith('.node'));
  if (addons.length !== 1) {
    throw new Error(`Expected one injected addon in ${out}, found ${addons.join(', ') || 'none'}.`);
  }
  run('strip', ['-x', join(out, addons[0])]);
};

const wasm = (env, out) => {
  prepare(env, ['sources', 'tools', 'prefixes']);
  writeHeader('W01');
  runTarget('prepare-delivery:inputs', env);
  runTarget('build-wasm', env);
  for (const name of ['geospec_engine_native.mjs', 'geospec_engine_native.wasm']) {
    copyFileSync(join(engineRoot, 'bindings/emscripten/generated', name), join(out, name));
  }
};

const main = () => {
  const { values, positionals } = parseArgs({ allowPositionals: true, options: { out: { type: 'string' } } });
  const [product] = positionals;
  if ((product !== 'native' && product !== 'wasm') || values.out === undefined) {
    throw new Error('usage: build-injected.mjs native|wasm --out <dir>');
  }
  const out = resolve(values.out);
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  const env = producerEnvironment();
  try {
    if (product === 'native') {
      native(env, out);
    } else {
      wasm(env, out);
    }
  } finally {
    rmSync(header, { force: true });
  }
  console.log(`S10 injected ${product} product: ${out}`);
};

try {
  main();
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
