const emit = (event) => {
  writeSync(3, `${JSON.stringify(event)}\n`);
};

const encoder = new TextEncoder();
const decoder = new TextDecoder();
const json = (value) => encoder.encode(JSON.stringify(value));
const parse = (bytes) => JSON.parse(decoder.decode(bytes));
const control = (method, requestId, fields) => ({
  method,
  requestId,
  protocolVersion: 3,
  registryVersion: 5,
  canonicalProfile: 'geospec-jcs-v1',
  ...fields,
});

const fixture = (matrix, name) => {
  const declared = matrix.fixtures[name];
  const bytes = new Uint8Array(readFileSync(join(engineRoot, matrix.fixtures.root, declared.path)));
  if (sha256(bytes) !== declared.sha256) {
    throw new Error(`Fixture ${declared.path} does not match its frozen SHA-256.`);
  }
  return bytes;
};

const stepRequest = (length, fields = {}) =>
  json(
    control('ingestSubject', 'admit', {
      format: 'step',
      frame: { coordinateSystem: 'z-up', sourceUnit: 'auto', outputUnit: 'mm' },
      ingestOptions: {},
      primaryByteLength: length,
      resources: [],
      ...fields,
    }),
  );

const meshRequest = (bytes) =>
  json(
    control('ingestSubject', 'admit-mesh', {
      contentHash: sha256(bytes),
      format: 'mesh-buffer-v1',
      frame: { coordinateSystem: 'z-up', unit: 'mm' },
    }),
  );

const claimRequest = (subjectHash, { capability, payload, workUnitBudget }) =>
  json(
    control('submitClaims', 'claim', {
      plan: {
        subjects: [{ slot: 'part', subjectHash }],
        claims: [
          { claimId: 'claim', capability, subjectSlots: ['part'], payload, polarity: 'positive', workUnitBudget },
        ],
      },
    }),
  );

const componentsClaim = (workUnitBudget) => ({
  capability: 'toHaveConnectedComponents',
  payload: { kind: 'connectedComponents', expected: { count: 1, toleranceMm: 0 } },
  workUnitBudget,
});

const resultBytes = (value) => (value instanceof Uint8Array ? value : value.canonicalResult);

/**
 * Run one engine operation and describe its outcome without letting it escape.
 * @param {Set<string>} typedCodes - Protocol error codes the engine defines.
 * @param {() => unknown} operation - The engine call.
 * @returns {{ outcome: string, code?: string, message?: string, sha256?: string, bytes?: Uint8Array }} Outcome.
 */
const attempt = (typedCodes, operation) => {
  try {
    const bytes = resultBytes(operation());
    return { outcome: 'success', sha256: sha256(bytes), bytes };
  } catch (error) {
    const code = /** @type {{ code?: unknown }} */ (error)?.code;
    const message = String(/** @type {{ message?: unknown }} */ (error)?.message ?? error);
    if (typeof code === 'string' && typedCodes.has(code) && message.length > 0) {
      return { outcome: 'typed-error', code, message };
    }
    if (error instanceof WebAssembly.RuntimeError) {
      return { outcome: 'trap', message };
    }
    return { outcome: 'untyped-error', code: String(code), message: `${error?.name}: ${message}` };
  }
};

const loadHost = async (host, consumer) => {
  const require = createRequire(join(resolve(consumer), 'package.json'));
  const entry = host === 'native' ? 'geospec-engine/node' : 'geospec-engine/wasm';
  const module = await import(pathToFileURL(require.resolve(entry)).href);
  if (host === 'wasm') {
    await module.initialize();
  }
  return module;
};

const treeState = (directory) => {
  if (!existsSync(directory)) {
    return [];
  }
  return readdirSync(directory, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => {
      const path = join(entry.parentPath, entry.name);
      return `${relative(directory, path)}:${statSync(path).size}`;
    })
    .sort();
};

/** Probe context: one host module, its engines, the fixtures and the recorded checks. */
class Probe {
  constructor(module, { host, matrix }) {
    this.module = module;
    this.host = host;
    this.matrix = matrix;
    this.typedCodes = new Set(matrix.abi.typedCodes);
    this.checks = [];
    this.caches = [];
    this.persistence = [];
    this.fault = fixture(matrix, 'fault');
    this.truncated = fixture(matrix, 'truncated');
    this.recoveryBytes = fixture(matrix, 'recovery');
  }

  engine({ isCached = true } = {}) {
    if (this.host !== 'native' || !isCached) {
      return new this.module.Engine();
    }
    const root = mkdtempSync(join(tmpdir(), 'geospec-s10-cache-'));
    const projectRoot = mkdtempSync(join(tmpdir(), 'geospec-s10-project-'));
    const engine = new this.module.Engine({ root, projectRoot });
    engine.flushCache();
    this.caches.push({ engine, root, before: treeState(root) });
    return engine;
  }

  try(operation) {
    return attempt(this.typedCodes, operation);
  }

  check(name, isOk, detail = {}) {
    this.checks.push({ name, ok: Boolean(isOk), ...detail });
  }

  typed(name, operation, expectedCode) {
    const { bytes: _bytes, ...result } = this.try(operation);
    const isOk = result.outcome === 'typed-error' && (expectedCode === undefined || result.code === expectedCode);
    this.check(name, isOk, result);
    return result;
  }

  physical(engine) {
    const snapshot = parse(engine.observations());
    return { physical: snapshot.physical, logical: snapshot.logical };
  }

  admit(engine) {
    return parse(engine.ingestSubject(stepRequest(this.fault.length), this.fault, [])).result.subject.subjectHash;
  }

  handle(engine, subjectHash) {
    return parse(engine.subjectHandle(json(control('subjectHandle', 'handle', { subjectHash })))).result.subjectHandle;
  }

  release(engine, subjectHandle) {
    return engine.releaseSubject(json(control('releaseSubject', 'release', { subjectHandle })));
  }

  /** Flush every cache and record whether the faults left any record behind. */
  recordPersistence() {
    for (const cache of this.caches) {
      try {
        cache.engine.flushCache();
      } catch {
        // A closed engine has already flushed on close.
      }
      const after = treeState(cache.root);
      this.persistence.push({ before: cache.before, after, unchanged: after.join('\n') === cache.before.join('\n') });
    }
  }

  recover(engine) {
    const { recovery } = this.matrix.fixtures;
    const ingest = engine.ingestSubject(stepRequest(this.recoveryBytes.length), this.recoveryBytes, []);
    const { subjectHash } = parse(ingest).result.subject;
    const claim = engine.processRequest(claimRequest(subjectHash, recovery));
    return { ingest: sha256(ingest), claim: sha256(claim) };
  }
}

const noAdmission = (probe, engine, before) => {
  const after = probe.physical(engine);
  probe.check('no-partial-admission', after.physical.admissions === before.physical.admissions, {
    admissionsBefore: before.physical.admissions,
    admissionsAfter: after.physical.admissions,
  });
};

const probeEmpty = (probe) => {
  const engine = probe.engine();
  const empty = new Uint8Array(0);
  const before = probe.physical(engine);
  probe.typed('step-empty', () => engine.ingestSubject(stepRequest(0), empty, []));
  probe.typed('mesh-empty', () => engine.ingestMesh(meshRequest(empty), empty));
  for (const method of ['processRequest', 'canonicalPlan', 'evaluatePlan', 'evaluateClaim', 'subjectHandle']) {
    probe.typed(`${method}-empty`, () => engine[method](empty));
  }
  probe.typed('releaseSubject-empty', () => engine.releaseSubject(empty));
  probe.typed('canonicalize-empty', () => probe.module.canonicalize(empty));
  noAdmission(probe, engine, before);
  return engine;
};

const stepFailures = (probe, engine, inputs) => {
  const before = probe.physical(engine);
  const codes = [];
  for (const [name, bytes] of inputs) {
    const result = probe.typed(name, () => engine.ingestSubject(stepRequest(bytes.length), bytes, []));
    codes.push(result.code);
  }
  noAdmission(probe, engine, before);
  return codes;
};

const probeTruncated = (probe) => {
  const engine = probe.engine();
  const codes = stepFailures(probe, engine, [
    ['truncated-step', probe.truncated],
    ['fault-prefix-1024', probe.fault.slice(0, 1024)],
    ['fault-prefix-half', probe.fault.slice(0, Math.floor(probe.fault.length / 2))],
  ]);
  emit({ event: 'step-codes', codes });
  return engine;
};

const probeGarbage = (probe) => {
  const engine = probe.engine();
  const small = xorshift32(0x53_10_00_03, 512);
  const large = xorshift32(0x53_10_00_04, 4096);
  const codes = stepFailures(probe, engine, [
    ['garbage-step-512', small],
    ['garbage-step-4096', large],
  ]);
  emit({ event: 'step-codes', codes });
  probe.typed('garbage-mesh', () => engine.ingestMesh(meshRequest(small), small));
  probe.typed('garbage-request', () => engine.processRequest(large));
  probe.typed('garbage-canonicalize', () => probe.module.canonicalize(small));
  return engine;
};

const probeLengths = (probe) => {
  const engine = probe.engine();
  const bytes = probe.fault;
  const before = probe.physical(engine);
  const cases = [
    ['primary-plus-one', { primaryByteLength: bytes.length + 1 }, []],
    ['primary-minus-one', { primaryByteLength: bytes.length - 1 }, []],
    ['primary-max-safe', { primaryByteLength: Number.MAX_SAFE_INTEGER }, []],
    ['primary-negative', { primaryByteLength: -1 }, []],
    ['primary-fraction', { primaryByteLength: bytes.length + 0.5 }, []],
    ['primary-string', { primaryByteLength: String(bytes.length) }, []],
    ['resource-short', { resources: [{ name: 'mesh.bin', byteLength: 10 }] }, [new Uint8Array(9)]],
    ['resource-undeclared', { resources: [] }, [new Uint8Array(4)]],
    ['resource-missing', { resources: [{ name: 'mesh.bin', byteLength: 4 }] }, []],
  ];
  for (const [name, fields, resources] of cases) {
    probe.typed(name, () => engine.ingestSubject(stepRequest(bytes.length, fields), bytes, resources));
  }
  noAdmission(probe, engine, before);
  return engine;
};

const probeRepeatedRelease = (probe) => {
  const engine = probe.engine();
  const subjectHandle = probe.handle(engine, probe.admit(engine));
  const first = probe.try(() => probe.release(engine, subjectHandle));
  probe.check('first-release', first.outcome === 'success' && parse(first.bytes).result.released === true);
  const second = probe.try(() => probe.release(engine, subjectHandle));
  probe.check('second-release-stale', second.outcome === 'success' && parse(second.bytes).result.released === false);
  const forged = probe.try(() => probe.release(engine, { ...subjectHandle, generation: '99' }));
  probe.check(
    'forged-generation',
    forged.outcome === 'typed-error' || (forged.outcome === 'success' && parse(forged.bytes).result.released === false),
    { outcome: forged.outcome, code: forged.code },
  );
  probe.recordPersistence();
  const closed = probe.try(() => {
    engine.close();
    engine.close();
    return new Uint8Array(0);
  });
  probe.check('close-twice', closed.outcome === 'success', { outcome: closed.outcome, message: closed.message });
  probe.typed('after-close', () => engine.processRequest(claimRequest('0'.repeat(64), componentsClaim(10))));
  return probe.engine();
};

const probeQueryAfterRelease = (probe) => {
  const engine = probe.engine();
  const subjectHash = probe.admit(engine);
  probe.release(engine, probe.handle(engine, subjectHash));
  const before = probe.physical(engine);
  probe.typed('claim-after-release', () => engine.processRequest(claimRequest(subjectHash, componentsClaim(1000))));
  probe.typed('one-call-after-release', () => engine.evaluateClaim(claimRequest(subjectHash, componentsClaim(1000))));
  probe.typed('handle-after-release', () => probe.handle(engine, subjectHash));
  const after = probe.physical(engine);
  probe.check('no-evaluation-or-backend-work', JSON.stringify(before) === JSON.stringify(after), { before, after });
  return engine;
};

const probeCrossSession = (probe) => {
  const owner = probe.engine();
  const other = probe.engine();
  const subjectHash = probe.admit(owner);
  const subjectHandle = probe.handle(owner, subjectHash);
  const before = probe.physical(other);
  probe.typed('foreign-release', () => probe.release(other, subjectHandle), 'invalid-request');
  probe.typed('foreign-claim', () => other.processRequest(claimRequest(subjectHash, componentsClaim(1000))));
  probe.check('no-foreign-work', JSON.stringify(before) === JSON.stringify(probe.physical(other)));
  probe.admit(other);
  probe.typed('foreign-release-after-admission', () => probe.release(other, subjectHandle), 'invalid-request');
  const own = probe.try(() => probe.release(owner, subjectHandle));
  probe.check('owner-release-unaffected', own.outcome === 'success' && parse(own.bytes).result.released === true);
  return owner;
};

const statusOf = (bytes) => parse(bytes).result.results[0];

const probeZeroBudget = (probe) => {
  const engine = probe.engine();
  const subjectHash = probe.admit(engine);
  probe.typed(
    'budget-zero',
    () => engine.processRequest(claimRequest(subjectHash, componentsClaim(0))),
    'invalid-claim',
  );
  const one = probe.try(() => engine.processRequest(claimRequest(subjectHash, componentsClaim(1))));
  const row = one.outcome === 'success' ? statusOf(one.bytes) : undefined;
  probe.check(
    'budget-one-refused',
    row?.status === 'refused' && row.diagnostics.some((diagnostic) => diagnostic.code === 'MATCHER_TIMEOUT'),
    { outcome: one.outcome, status: row?.status, diagnostics: row?.diagnostics?.map(({ code }) => code) },
  );
  return engine;
};

const probeBoundaryBudget = (probe) => {
  const engine = probe.engine();
  const subjectHash = probe.admit(engine);
  const evaluate = (budget) => engine.processRequest(claimRequest(subjectHash, componentsClaim(budget)));
  let boundary;
  for (let budget = 1; budget <= probe.matrix.limits.budgetScanLimit && boundary === undefined; budget += 1) {
    if (statusOf(evaluate(budget)).status !== 'refused') {
      boundary = budget;
    }
  }
  probe.check('boundary-found', boundary !== undefined && boundary > 1, { boundary });
  if (boundary === undefined || boundary <= 1) {
    return engine;
  }
  const below = statusOf(evaluate(boundary - 1));
  probe.check(
    'below-refused',
    below.status === 'refused' && below.diagnostics.some((diagnostic) => diagnostic.code === 'MATCHER_TIMEOUT'),
  );
  const at = statusOf(evaluate(boundary));
  const above = statusOf(evaluate(boundary + 1));
  probe.check('at-and-above-agree', JSON.stringify(at) === JSON.stringify(above), { status: at.status });
  const first = [boundary - 1, boundary, boundary + 1].map((budget) => sha256(evaluate(budget)));
  const again = [boundary - 1, boundary, boundary + 1].map((budget) => sha256(evaluate(budget)));
  probe.check('repeatable', first.join(',') === again.join(','), { digests: first });
  return engine;
};

