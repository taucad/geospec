/** @type {(bytes: Uint8Array | string) => string} */
export const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');

/**
 * Fixed pseudo-random bytes: the same sequence for a seed on every run and host.
 * @param {number} seed - Nonzero 32-bit seed.
 * @param {number} length - Byte count.
 * @returns {Uint8Array<ArrayBuffer>} Generated bytes.
 */
export const xorshift32 = (seed, length) => {
  // oxlint-disable no-bitwise -- Xorshift is defined over unsigned 32-bit shifts.
  let state = seed >>> 0 || 1;
  const bytes = new Uint8Array(length);
  for (let index = 0; index < length; index += 1) {
    state ^= state << 13;
    state >>>= 0;
    state ^= state >>> 17;
    state ^= state << 5;
    state >>>= 0;
    bytes[index] = state & 0xff;
  }
  // oxlint-enable no-bitwise -- End of the generator.
  return bytes;
};

/**
 * Classify how an isolated probe process ended.
 * @param {{ status: number | null, signal: string | null, timedOut: boolean, events: { event: string }[] }} exit - Process outcome.
 * @returns {string} `completed`, `infrastructure-failure` (killed or crashed) or `exited`.
 */
export const classifyExit = ({ status, signal, timedOut, events }) => {
  if (timedOut || signal !== null) {
    return 'infrastructure-failure';
  }
  if (status === 0 && events.some(({ event }) => event === 'done')) {
    return 'completed';
  }
  return 'exited';
};

/**
 * Replace each embedded producer identity digest with zeros, so two builds of
 * different sources compare only their code and data.
 * @param {Uint8Array} bytes - Binary bytes.
 * @returns {{ bytes: Buffer, identities: number }} Masked copy and the masked digest count.
 */
export const maskProducerIdentity = (bytes) => {
  const text = Buffer.from(bytes).toString('latin1');
  let identities = 0;
  const masked = text.replaceAll(/sha256:[0-9a-f]{64}/gu, () => {
    identities += 1;
    return `sha256:${'0'.repeat(64)}`;
  });
  return { bytes: Buffer.from(masked, 'latin1'), identities };
};

/**
 * Count each injection marker in a binary.
 * @param {Uint8Array} bytes - Binary bytes.
 * @returns {Record<string, number>} Occurrences per marker.
 */
export const findMarkers = (bytes) => {
  const text = Buffer.from(bytes).toString('latin1');
  return Object.fromEntries(injectionMarkers.map((marker) => [marker, text.split(marker).length - 1]));
};

/**
 * Resolve one cell from its ledger entries and matrix declaration.
 * @param {any} cell - The matrix cell.
 * @param {{ status: string, reason?: string, host?: string }[]} entries - Ledger entries for the cell.
 * @param {Set<string>} conditional - Conditional cell IDs.
 * @returns {{ cell: string, status: string, conditional: boolean, reason: string, hosts: Record<string, string> }} Resolution.
 */
export const resolveCell = (cell, entries, conditional) => {
  const isConditional = conditional.has(cell.id);
  const hosts = Object.fromEntries(entries.map((entry) => [entry.host ?? 'unknown', entry.status]));
  const resolved = (status, reason) => ({ cell: cell.id, status, conditional: isConditional, reason, hosts });
  if (cell.disposition === 'unsupported' || cell.disposition === 'tool-gap') {
    return resolved('unsupported', cell.reason);
  }
  if (entries.length === 0) {
    return resolved('missing', 'No ledger entry ran this cell.');
  }
  const reasons = (status) =>
    entries
      .filter((entry) => entry.status === status)
      .map((entry) => `${entry.host}: ${entry.reason ?? ''}`)
      .join('; ');
  if (entries.some((entry) => entry.status === 'fail')) {
    return resolved('fail', reasons('fail'));
  }
  if (entries.some((entry) => entry.status === 'pending')) {
    return resolved('pending', reasons('pending'));
  }
  if (entries.some((entry) => entry.status === 'pass')) {
    return resolved('pass', reasons('unsupported'));
  }
  return resolved('unsupported', reasons('unsupported'));
};

/**
 * Apply the S10 acceptance rule: every non-conditional cell passes, every
 * conditional cell passes or is unsupported with a reason. Scope
 * `non-injected` reports pending injected cells without failing on them.
 * @param {any} matrix - The frozen matrix.
 * @param {{ entries: any[] }[]} ledgers - Every ledger produced by the run.
 * @param {'all' | 'non-injected'} scope - Which cells must resolve.
 * @returns {{ passed: boolean, cells: ReturnType<typeof resolveCell>[] }} The gate decision.
 */
export const gate = (matrix, ledgers, scope) => {
  const conditional = new Set(matrix.predeclared.conditional);
  const entries = ledgers.flatMap((ledger) => ledger.entries);
  const cells = matrix.cells.map((cell) =>
    resolveCell(
      cell,
      entries.filter((entry) => entry.cell === cell.id),
      conditional,
    ),
  );
  const acceptable = (resolution) => {
    const declared = matrix.cells.find((cell) => cell.id === resolution.cell);
    if (resolution.status === 'pass') {
      return true;
    }
    if (resolution.status === 'unsupported') {
      return resolution.conditional && resolution.reason.length > 0;
    }
    return scope === 'non-injected' && declared.disposition === 'injected' && resolution.status === 'pending';
  };
  return { passed: cells.every((resolution) => acceptable(resolution)), cells };
};

