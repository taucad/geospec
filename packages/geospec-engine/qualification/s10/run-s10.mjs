const fetchBaseline = (version) => {
  const directory = mkdtempSync(join(tmpdir(), 'geospec-s10-baseline-'));
  const names = JSON.parse(readFileSync(join(repositoryRoot, 'names.json'), 'utf8'));
  const specs = [`${names.engine.npm}@${version}`, `${names.engine.platformPackagePrefix}darwin-arm64@${version}`];
  run('npm', ['pack', '--loglevel=warn', ...specs, '--pack-destination', directory], { cwd: directory });
  return readdirSync(directory)
    .filter((name) => name.endsWith('.tgz'))
    .flatMap((name) => binaries(extract(join(directory, name))));
};

const compareWithBaseline = (files, baseline) =>
  files.flatMap((file) => {
    const match = baseline.find((candidate) => basename(candidate) === basename(file));
    if (match === undefined) {
      return [];
    }
    const current = maskProducerIdentity(readFileSync(file));
    const previous = maskProducerIdentity(readFileSync(match));
    let differing = 0;
    for (let index = 0; index < Math.min(current.bytes.length, previous.bytes.length); index += 1) {
      if (current.bytes[index] !== previous.bytes[index]) {
        differing += 1;
      }
    }
    return [
      {
        file: basename(file),
        sizes: [previous.bytes.length, current.bytes.length],
        rawEqual: readFileSync(file).equals(readFileSync(match)),
        identities: [previous.identities, current.identities],
        maskedEqual: current.bytes.equals(previous.bytes),
        differingBytes: differing,
      },
    ];
  });

const releaseCheck = (values) => {
  const candidate = resolve(values.candidate);
  const files = readdirSync(candidate)
    .filter((name) => /\.(?:tgz|node|wasm)$/u.test(name))
    .flatMap((name) => (name.endsWith('.tgz') ? binaries(extract(join(candidate, name))) : [join(candidate, name)]));
  if (values.wheels !== undefined) {
    for (const wheel of readdirSync(resolve(values.wheels)).filter((name) => name.endsWith('.whl'))) {
      const directory = mkdtempSync(join(tmpdir(), 'geospec-s10-wheel-'));
      run('unzip', ['-q', join(resolve(values.wheels), wheel), '-d', directory]);
      files.push(...binaries(directory));
    }
  }
  const isExpected = values['expect-markers'] === true;
  const inspected = files.map((file) => {
    const markers = findMarkers(readFileSync(file));
    const count = Object.values(markers).reduce((total, value) => total + value, 0); // oxlint-disable-line unicorn/no-array-reduce -- One sum.
    return {
      file: basename(file),
      sha256: sha256(readFileSync(file)),
      markers,
      ok: isExpected ? count > 0 : count === 0,
    };
  });
  const baseline =
    values['baseline-version'] === undefined
      ? undefined
      : compareWithBaseline(files, fetchBaseline(values['baseline-version']));
  return {
    expectMarkers: isExpected,
    passed: inspected.length > 0 && inspected.every(({ ok }) => ok),
    inspected,
    baseline,
  };
};

const gateCommand = (values, ledgerPaths) => {
  const matrix = readMatrix();
  const ledgers = ledgerPaths.map((path) => JSON.parse(readFileSync(path, 'utf8')));
  const decision = gate(matrix, ledgers, values.scope ?? 'all');
  const rows = decision.cells.map(
    ({ cell, status, conditional, reason, hosts }) =>
      `| ${cell} | ${status} | ${conditional ? 'yes' : 'no'} | ${Object.entries(hosts)
        .map(([host, hostStatus]) => `${host}: ${hostStatus}`)
        .join(', ')} | ${reason.replaceAll('|', '/').slice(0, 300)} |`,
  );
  const markdown = [
    `### S10 qualification (${values.scope ?? 'all'}): ${decision.passed ? 'pass' : 'fail'}`,
    '',
    '| Cell | Status | Conditional | Hosts | Reason |',
    '| --- | --- | --- | --- | --- |',
    ...rows,
    '',
  ].join('\n');
  if (process.env['GITHUB_STEP_SUMMARY']) {
    writeFileSync(process.env['GITHUB_STEP_SUMMARY'], markdown, { flag: 'a' });
  }
  console.log(markdown);
  return { schema: 'geospec-s10-summary-v1', scope: values.scope ?? 'all', ...decision };
};

