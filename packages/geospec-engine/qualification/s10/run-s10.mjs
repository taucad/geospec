  process.stdout.write(result.stdout);
  process.stderr.write(result.stderr);
  const summaries = [...result.stdout.matchAll(/^test result: (\w+)\. (\d+) passed; (\d+) failed/gmu)].map((match) => ({
    result: match[1],
    passed: Number(match[2]),
    failed: Number(match[3]),
  }));
  const passed = summaries.reduce((total, summary) => total + summary.passed, 0); // oxlint-disable-line unicorn/no-array-reduce -- One sum.
