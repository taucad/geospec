/** Generate one fuzz input for a seed and case; the same input on every host. */
const fuzzInput = (probe, { seed, kind }) => {
  const random = xorshift32(seed, 64 + (seed % 1024));
  if (kind === 'step-mutated' || kind === 'request-mutated') {
    const base =
      kind === 'step-mutated' ? Uint8Array.from(probe.fault) : claimRequest('0'.repeat(64), componentsClaim(1000));
    const positions = xorshift32(seed ^ 0x5a_5a_5a_5a, 16); // oxlint-disable-line no-bitwise -- Seed split.
    for (let index = 0; index < 1 + (seed % 8); index += 1) {
      const offset = (positions[index * 2] * 256 + positions[index * 2 + 1]) % base.length;
      base[offset] = random[index];
    }
    return base;
  }
  return random;
};

const fuzzCall = (probe, engine, { kind, input }) => {
  switch (kind) {
    case 'step-random':
    case 'step-mutated': {
      return () => engine.ingestSubject(stepRequest(input.length), input, []);
    }
    case 'mesh-random': {
      return () => engine.ingestMesh(meshRequest(input), input);
    }
    case 'request-random':
    case 'request-mutated': {
      return () => engine.processRequest(input);
    }
    default: {
      return () => probe.module.canonicalize(input);
    }
  }
};

const runFuzz = (probe, from) => {
  const { seeds, cases } = probe.matrix.fuzz;
  const inputs = seeds.flatMap((seed) => cases.map((kind) => ({ seed, kind })));
  const engine = probe.engine();
  for (let index = from; index < inputs.length; index += 1) {
    const { seed, kind } = inputs[index];
    const input = fuzzInput(probe, { seed, kind });
    emit({ event: 'begin', index, seed, kind, sha256: sha256(input) });
    const { bytes: _bytes, ...result } = probe.try(fuzzCall(probe, engine, { kind, input }));
    emit({ event: 'end', index, ...result });
    if (result.outcome === 'trap') {
      // A trapped WASM instance is not reused; the parent resumes in a new process.
      return;
    }
  }
  emit({ event: 'done' });
};

const child = async (values) => {
  const matrix = readMatrix();
  const probe = new Probe(await loadHost(values.host, values.consumer), { host: values.host, matrix });
  const mode = values.mode ?? 'cell';
  if (mode === 'control') {
    emit({ event: 'recovery', ...probe.recover(probe.engine()) });
  } else if (mode === 'hang') {
    probe.admit(probe.engine());
    emit({ event: 'admitted' });
    Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0);
    emit({ event: 'cancelled' });
  } else if (mode === 'fuzz') {
    runFuzz(probe, Number(values.from ?? 0));
  } else if (mode === 'injected') {
    // An injected build is never a verified producer, so it cannot open the authenticated cache.
    const engine = probe.engine({ isCached: false });
    const before = probe.physical(engine);
    const result = probe.try(() => engine.ingestSubject(stepRequest(probe.fault.length), probe.fault, []));
    emit({ event: 'returned', outcome: result.outcome, code: result.code, message: result.message });
    if (result.outcome === 'typed-error') {
      emit({
        event: 'admissions',
        before: before.physical.admissions,
        after: probe.physical(engine).physical.admissions,
      });
      emit({ event: 'recovery', ...probe.recover(engine) });
    }
  } else {
    const survivor = ordinaryProbes.get(values.cell)(probe);
    if (values.cell !== 'L01') {
      probe.recordPersistence();
    }
    emit({ event: 'checks', checks: probe.checks, persistence: probe.persistence });
    emit({ event: 'recovery', ...probe.recover(survivor) });
  }
  emit({ event: 'memory', maxRssBytes: process.resourceUsage().maxRSS * 1024 });
  emit({ event: 'done' });
};

