/**
 * Run one probe process and collect its events.
 * @param {{ host: string, consumer: string, mode: string, cell?: string, from?: number, env?: NodeJS.ProcessEnv, timeoutMs: number }} options - Probe selection.
 * @returns {{ status: number | null, signal: string | null, timedOut: boolean, events: any[], stderr: string }} Outcome.
 */
const spawnProbe = ({ host, consumer, mode, cell, from, env, timeoutMs }) => {
  const args = [self, 'child', '--host', host, '--consumer', consumer, '--mode', mode];
  if (cell !== undefined) {
    args.push('--cell', cell);
  }
  if (from !== undefined) {
    args.push('--from', String(from));
  }
  const result = spawnSync(process.execPath, args, {
    cwd: tmpdir(),
    env: env ?? process.env,
    stdio: ['ignore', 'pipe', 'pipe', 'pipe'],
    timeout: timeoutMs,
    killSignal: 'SIGKILL',
    maxBuffer: 64 * 1024 ** 2,
  });
  const events = String(result.output[3] ?? '')
    .split('\n')
    .filter((line) => line.length > 0)
    .map((line) => JSON.parse(line));
  return {
    status: result.status,
    signal: result.signal,
    timedOut: result.error?.code === 'ETIMEDOUT',
    events,
    stderr: String(result.stderr ?? '').slice(-2000),
  };
};

const lastEvent = (run, name) => run.events.findLast(({ event }) => event === name);

const sameRecovery = (recovery, controlDigests) =>
  recovery !== undefined && recovery.ingest === controlDigests.ingest && recovery.claim === controlDigests.claim;

/** Ledger builder for one host run. */
class Ledger {
  constructor(host) {
    this.host = host;
    this.entries = [];
  }

  add(cell, status, { reason = '', evidence = {} } = {}) {
    this.entries.push({ cell, host: this.host, status, reason, evidence });
  }
}

const runOrdinary = (context, cell) => {
  const { matrix, ledger, controlDigests } = context;
  const runs = [];
  for (let rep = 1; rep <= matrix.predeclared.ordinaryRepetitions; rep += 1) {
    runs.push(spawnProbe({ ...context.probe, mode: 'cell', cell, timeoutMs: matrix.limits.cellTimeoutMs }));
  }
  const failures = [];
  const summaries = runs.map((run, index) => {
    const checks = lastEvent(run, 'checks')?.checks ?? [];
    const memory = lastEvent(run, 'memory')?.maxRssBytes;
    const recovery = lastEvent(run, 'recovery');
    const exit = classifyExit(run);
    if (exit !== 'completed') {
      failures.push(`repetition ${index + 1} ended ${exit} (${run.status ?? run.signal}): ${run.stderr}`);
    }
    for (const failed of checks.filter(({ ok }) => !ok)) {
      failures.push(`repetition ${index + 1} check ${failed.name} failed: ${JSON.stringify(failed)}`);
    }
    if (memory === undefined || memory > matrix.limits.maxRssBytes) {
      failures.push(`repetition ${index + 1} peak RSS ${memory} exceeds ${matrix.limits.maxRssBytes}`);
    }
    context.recoveries.push({ cell, rep: index + 1, recovery, equal: sameRecovery(recovery, controlDigests) });
    context.persistence.push(...(lastEvent(run, 'checks')?.persistence ?? []).map((entry) => ({ cell, ...entry })));
    context.stepCodes.push(
      ...run.events
        .filter(({ event }) => event === 'step-codes')
        .flatMap(({ codes }) => codes.map((code) => ({ cell, code }))),
    );
    const signature = sha256(JSON.stringify(checks.map(({ name, ok, outcome, code }) => [name, ok, outcome, code])));
    return { signature, maxRssBytes: memory, checks };
  });
  if (new Set(summaries.map(({ signature }) => signature)).size !== 1) {
    failures.push('repetitions disagree');
  }
  ledger.add(cell, failures.length === 0 ? 'pass' : 'fail', {
    reason: failures.join('; '),
    evidence: { repetitions: summaries },
  });
};

const runWatchdog = (context) => {
  const { matrix, ledger } = context;
  const failures = [];
  const evidence = [];
  for (let rep = 1; rep <= matrix.predeclared.destructiveRepetitions; rep += 1) {
    const run = spawnProbe({ ...context.probe, mode: 'hang', timeoutMs: matrix.limits.watchdogMs });
    const isAdmitted = run.events.some(({ event }) => event === 'admitted');
    const classification = classifyExit(run);
    const synthesized = run.events.filter(({ event }) => event === 'cancelled' || event === 'done');
    evidence.push({ rep, isAdmitted, classification, signal: run.signal, synthesized: synthesized.length });
    if (!isAdmitted || classification !== 'infrastructure-failure' || synthesized.length > 0) {
      failures.push(`repetition ${rep}: admitted=${isAdmitted} classification=${classification}`);
    }
    context.afterDestructive(`X02 repetition ${rep}`);
  }
  ledger.add('X02', failures.length === 0 ? 'pass' : 'fail', { reason: failures.join('; '), evidence });
};

/**
 * Z01 accepts a typed error, a success, or an isolated deliberate abort (a
 * Rust panic under panic=abort). A hang, an untyped error, a WASM trap or any
 * other crash signal is a failure: a trap or a fault signal can come from
 * undefined behaviour, which the cell excludes.
 */
const acceptedFuzzOutcomes = new Set(['success', 'typed-error', 'abort']);

const fuzzDeath = (run) => {
  if (run.timedOut) {
    return 'hang';
  }
  return run.signal === 'SIGABRT' ? 'abort' : `crash:${run.signal ?? run.status}`;
};

const runFuzzCell = (context) => {
  const { matrix, ledger } = context;
  const total = matrix.fuzz.seeds.length * matrix.fuzz.cases.length;
  const records = [];
  const failures = [];
  let from = 0;
  while (from < total) {
    const run = spawnProbe({ ...context.probe, mode: 'fuzz', from, timeoutMs: matrix.limits.fuzzTimeoutMs });
    const ends = new Map(run.events.filter(({ event }) => event === 'end').map((end) => [end.index, end]));
    let next = total;
    for (const begin of run.events.filter(({ event }) => event === 'begin')) {
      const end = ends.get(begin.index);
      const outcome = end?.outcome ?? fuzzDeath(run);
      const record = {
        index: begin.index,
        seed: begin.seed,
        kind: begin.kind,
        sha256: begin.sha256,
        outcome,
        code: end?.code,
      };
      if (!acceptedFuzzOutcomes.has(outcome)) {
        Object.assign(record, { message: end?.message, stderr: run.stderr });
        failures.push(`seed ${begin.seed} ${begin.kind} (input ${begin.sha256}): ${outcome} ${end?.message ?? ''}`);
      }
      records.push(record);
      if (end === undefined || outcome === 'trap') {
        next = begin.index + 1;
      }
    }
    const memory = lastEvent(run, 'memory')?.maxRssBytes;
    if (memory !== undefined && memory > matrix.limits.maxRssBytes) {
      failures.push(`peak RSS ${memory} exceeds ${matrix.limits.maxRssBytes}`);
    }
    if (next === total && classifyExit(run) !== 'completed') {
      failures.push(`fuzz process ended ${classifyExit(run)} without an attributable seed: ${run.stderr}`);
    }
    if (next < total) {
      context.afterDestructive(`Z01 after input ${next - 1}`);
    }
    from = next;
  }
  context.stepCodes.push(
    ...records.filter(({ kind }) => kind.startsWith('step-')).map(({ code }) => ({ cell: 'Z01', code })),
  );
  if (records.length !== total) {
    failures.push(`ran ${records.length} of ${total} inputs`);
  }
  ledger.add('Z01', failures.length === 0 ? 'pass' : 'fail', { reason: failures.join('; '), evidence: { records } });
};

/**
 * Failures of one injected repetition's outcome against what its cell expects.
 * @param {string} cell The injected cell.
 * @param {string} outcome The repetition's classified outcome.
 * @param {{ message?: string } | undefined} returned The probe's last returned event.
 * @returns {string[]} One message per unmet expectation.
 */
const injectedOutcomeFailures = (cell, outcome, returned) => {
  const failures = [];
  if (outcome === 'success' || outcome === 'untyped-error') {
    failures.push(`${outcome} ${returned?.message ?? ''}`);
  }
  if (cell === 'C01' && !(outcome === 'typed-error' && returned.message.includes('geospec-s10-inject C01'))) {
    failures.push(`the bridge did not translate the injected exception (${outcome})`);
  }
  if (cell === 'W01' && outcome !== 'trap') {
    failures.push(`expected a WASM trap, observed ${outcome}`);
  }
  return failures;
};

const runInjected = (context, { cell, consumer }) => {
  const { matrix, ledger } = context;
  const failures = [];
  const evidence = [];
  for (let rep = 1; rep <= matrix.predeclared.destructiveRepetitions; rep += 1) {
    const env = { ...process.env, GEOSPEC_S10_FAULT: cell };
    const run = spawnProbe({
      ...context.probe,
      consumer,
      env,
      mode: 'injected',
      timeoutMs: matrix.limits.cellTimeoutMs,
    });
    const returned = lastEvent(run, 'returned');
    const admissions = lastEvent(run, 'admissions');
    const recovery = lastEvent(run, 'recovery');
    const classification = classifyExit(run);
    const outcome = returned?.outcome ?? classification;
    evidence.push({
      rep,
      outcome,
      code: returned?.code,
      message: returned?.message,
      signal: run.signal,
      status: run.status,
    });
    failures.push(
      ...injectedOutcomeFailures(cell, outcome, returned).map((failure) => `repetition ${rep}: ${failure}`),
    );
    if (outcome === 'typed-error') {
      if (admissions === undefined || admissions.before !== admissions.after) {
        failures.push(`repetition ${rep}: partial admission ${JSON.stringify(admissions)}`);
      }
      context.recoveries.push({ cell, rep, recovery, equal: sameRecovery(recovery, context.controlDigests) });
    } else {
      context.afterDestructive(`${cell} repetition ${rep}`);
      const reset = context.fresh.at(-1);
      evidence.at(-1).processReset = reset;
      if (!reset.equal) {
        failures.push(`repetition ${rep}: the new process did not recover the clean-session control`);
      }
    }
  }
  if (new Set(evidence.map(({ outcome }) => outcome)).size !== 1) {
    failures.push('the reproduction disagrees with the first run');
  }
  ledger.add(cell, failures.length === 0 ? 'pass' : 'fail', { reason: failures.join('; '), evidence });
};

const runHost = (values) => {
  const matrix = readMatrix();
  const { host } = values;
  const consumer = resolve(values.consumer);
  const ledger = new Ledger(host);
  const selected = new Set(values.cells?.split(',') ?? matrix.cells.map(({ id }) => id));
  const control = spawnProbe({ host, consumer, mode: 'control', timeoutMs: matrix.limits.cellTimeoutMs });
  const controlDigests = lastEvent(control, 'recovery');
  if (controlDigests === undefined) {
    throw new Error(`The clean-session control failed on ${host}: ${control.stderr}`);
  }
  const context = {
    matrix,
    ledger,
    controlDigests,
    probe: { host, consumer },
    recoveries: [],
    persistence: [],
    stepCodes: [],
    fresh: [],
    afterDestructive: (after) => {
      const run = spawnProbe({ host, consumer, mode: 'control', timeoutMs: matrix.limits.cellTimeoutMs });
      const recovery = lastEvent(run, 'recovery');
      context.fresh.push({ after, recovery, equal: sameRecovery(recovery, controlDigests) });
    },
  };
  for (const cell of matrix.cells.filter(({ id }) => selected.has(id))) {
    const runners = cell.runners ?? [];
    if (ordinaryProbes.has(cell.id)) {
      runOrdinary(context, cell.id);
    } else if (cell.id === 'X02') {
      runWatchdog(context);
    } else if (cell.id === 'Z01') {
      runFuzzCell(context);
    } else if (runners.includes(host === 'native' ? 'injected-native' : 'injected-wasm')) {
      if (values['injected-consumer'] === undefined) {
        ledger.add(cell.id, 'pending', { reason: 'No injected build was supplied to this run.' });
      } else {
        runInjected(context, { cell: cell.id, consumer: resolve(values['injected-consumer']) });
      }
    }
  }
  resolveDerivedCells(context, selected);
  return {
    schema: 'geospec-s10-ledger-v1',
    host,
    runtime: process.version,
    platform: `${process.platform}-${process.arch}`,
    matrixSha256: sha256(readFileSync(join(here, 'matrix.json'))),
    candidate: candidateIdentity(consumer),
    control: controlDigests,
    entries: ledger.entries,
  };
};

const resolveDerivedCells = (context, selected) => {
  const { ledger, recoveries, persistence, stepCodes } = context;
  if (selected.has('H01')) {
    const unequal = recoveries.filter(({ equal }) => !equal);
    ledger.add('H01', recoveries.length > 0 && unequal.length === 0 ? 'pass' : 'fail', {
      reason:
        recoveries.length === 0
          ? 'No contained fault ran.'
          : unequal.map(({ cell, rep }) => `${cell}#${rep}`).join(', '),
      evidence: { control: context.controlDigests, recoveries },
    });
  }
  if (selected.has('H02')) {
    const { fresh } = context;
    const unequal = fresh.filter(({ equal }) => !equal);
    ledger.add('H02', fresh.length > 0 && unequal.length === 0 ? 'pass' : 'fail', {
      reason: fresh.length === 0 ? 'No process, trap or kill fault ran.' : unequal.map(({ after }) => after).join(', '),
      evidence: { control: context.controlDigests, fresh },
    });
  }
  if (selected.has('P01')) {
    if (ledger.host === 'native') {
      const changed = persistence.filter(({ unchanged }) => !unchanged);
      ledger.add('P01', persistence.length > 0 && changed.length === 0 ? 'pass' : 'fail', {
        reason: changed.map(({ cell }) => cell).join(', '),
        evidence: { inspected: persistence.length, changed },
      });
    } else {
      ledger.add('P01', 'unsupported', { reason: 'The WASM host has no persistent store.' });
    }
  }
  if (selected.has('C02')) {
    const reached = stepCodes.filter(({ code }) => code === 'backend-failure');
    const observed = [...new Set(stepCodes.map(({ code }) => code).filter((code) => code !== undefined))].sort();
    if (reached.length > 0) {
      ledger.add('C02', 'pass', { evidence: { reached } });
    } else {
      ledger.add('C02', 'unsupported', {
        reason: `No predeclared malformed STEP input reached the bridge's exception guard; observed codes: ${observed.join(', ')}.`,
        evidence: { observed },
      });
    }
  }
};

const candidateIdentity = (consumer) => {
  const identity = {};
  const modules = join(consumer, 'node_modules');
  for (const name of existsSync(modules) ? readdirSync(modules) : []) {
    if (name.startsWith('geospec-engine')) {
      const manifest = JSON.parse(readFileSync(join(modules, name, 'package.json'), 'utf8'));
      identity[name] = manifest.version;
    }
  }
  return identity;
};

