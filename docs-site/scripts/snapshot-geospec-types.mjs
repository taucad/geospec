// Snapshot the published `geospec` package's TypeScript declarations into `types/geospec/`, so the
// API page's type tables render the types readers install without the package's dependency tree
// (its runtime pulls in code kernels of about 130 MB). The script is the only writer of that
// directory: `node scripts/snapshot-geospec-types.mjs <version>` downloads the exact tarball with
// `npm pack`, copies every `dist/**/*.d.mts` file, rewrites each bare import (`@taucad/runtime/types`,
// `zod`, …) to a generated stub that names the imported types, and records the tarball's integrity
// hash and version in `types/geospec/manifest.json`. Relative imports stay as published.
import { execFileSync } from 'node:child_process';
import { globSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative } from 'node:path';

const version = process.argv[2];
if (version === undefined || !/^\d+\.\d+\.\d+(?:-[\w.]+)?$/u.test(version)) {
  throw new Error('usage: node scripts/snapshot-geospec-types.mjs <exact version>');
}
const out = join(import.meta.dirname, '..', 'types', 'geospec');
const work = mkdtempSync(join(tmpdir(), 'geospec-types-'));

/**
 * Types the stubs spell out instead of `unknown`, because a table shows them by shape.
 * @type {Readonly<Record<string, string>>}
 */
const knownStubTypes = {
  JSONValue: 'string | number | boolean | null | JSONValue[] | { readonly [key: string]: JSONValue }',
  KernelIssueCode: 'string',
};

const stubFileOf = (specifier) => `stubs/${specifier.replaceAll(/[@/]/gu, '_').replace(/^_/u, '')}.d.mts`;

const bareImport = /^import (?<typeOnly>type )?\{(?<names>[^}]*)\} from "(?<specifier>[^."][^"]*)";$/u;

/**
 * Rewrite one bare import to the stub that stands in for its package, recording the names the stub
 * must declare.
 * @param {string} statement - The import statement as published.
 * @param {string} target - The declaration file being written, so the stub path is relative to it.
 * @param {Map<string, Set<string>>} stubs - The names each package's stub declares; the call adds to it.
 * @returns {string} The rewritten statement.
 */
const rewriteImport = (statement, target, stubs) => {
  const { typeOnly = '', names = '', specifier = '' } = bareImport.exec(statement)?.groups ?? {};
  const set = stubs.get(specifier) ?? new Set();
  for (const name of names.split(',')) {
    const bare = name
      .trim()
      .replace(/^type /u, '')
      .split(/\s+as\s+/u)[0];
    if (bare !== '') {
      set.add(bare);
    }
  }
  stubs.set(specifier, set);
  // The import names the `.mjs` module, which TypeScript resolves to the sibling `.d.mts` stub.
  const path = relative(dirname(target), join(out, stubFileOf(specifier)))
    .replaceAll('\\', '/')
    .replace(/\.d\.mts$/u, '.mjs');
  return `import ${typeOnly}{${names}} from "${path.startsWith('.') ? path : `./${path}`}";`;
};

try {
  const [packed] = JSON.parse(
    execFileSync('npm', ['pack', `geospec@${version}`, '--json', '--pack-destination', work], { encoding: 'utf8' }),
  );
  execFileSync('tar', ['xzf', join(work, packed.filename), '-C', work]);
  const dist = join(work, 'package', 'dist');
  const files = globSync('**/*.d.mts', { cwd: dist }).toSorted();
  if (files.length === 0) {
    throw new Error('the tarball has no declaration files');
  }
  rmSync(out, { recursive: true, force: true });
  /** @type {Map<string, Set<string>>} */
  const stubs = new Map();
  for (const file of files) {
    const target = join(out, file);
    const text = readFileSync(join(dist, file), 'utf8')
      .replaceAll(/^import (?:type )?\{[^}]*\} from "[^."][^"]*";$/gmu, (statement) =>
        rewriteImport(statement, target, stubs),
      )
      // A bare side-effect import carries no types.
      .replaceAll(/^import "[^."][^"]*";\n/gmu, '');
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, text);
  }
  for (const [specifier, names] of stubs) {
    // A name the table does not spell out is `any` with spare type parameters, so a declaration that
    // applies type arguments, `Pick` or an indexed access to it still resolves.
    const lines = [...names]
      .toSorted()
      .map((name) =>
        name in knownStubTypes
          ? `export type ${name} = ${knownStubTypes[name]};`
          : `export type ${name}<_A = unknown, _B = unknown, _C = unknown> = any;`,
      );
    mkdirSync(join(out, 'stubs'), { recursive: true });
    writeFileSync(
      join(out, stubFileOf(specifier)),
      `// Stub for "${specifier}": the names the published declarations import from it, so the type tables\n// resolve them by name. Generated by scripts/snapshot-geospec-types.mjs.\n${lines.join('\n')}\n`,
    );
  }
  const manifest = {
    name: packed.name,
    version: packed.version,
    integrity: packed.integrity,
    shasum: packed.shasum,
    files,
    stubs: Object.fromEntries([...stubs].map(([specifier, names]) => [specifier, [...names].toSorted()])),
  };
  writeFileSync(join(out, 'manifest.json'), `${JSON.stringify(manifest, undefined, 2)}\n`);
  console.log(`${files.length} declaration files and ${stubs.size} stubs from ${packed.name}@${packed.version}`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
